import type { Block, Difficulty, OptionId, Question } from "@/lib/content/types";

// 本サイト独自問題（拡張セット）。opts / notes は [正解, 誤答1, 誤答2, 誤答3] の順に記述し、
// ans で指定した位置に正解を配置して a/i/u/e の選択肢を組み立てる。
const LESSON_OF: Record<string, string> = {
  "ops-monitoring": "ops/monitoring-vuln",
  "ops-vuln": "ops/monitoring-vuln",
  "ops-incident-response": "ops/incident-response",
  "ops-insurance": "ops/incident-response",
  "ops-backup": "ops/backup-bcp",
  "ops-bcp": "ops/backup-bcp",
};

const LETTERS: OptionId[] = ["a", "i", "u", "e"];

type Quad = readonly [string, string, string, string];

interface Spec {
  id: string;
  disp?: boolean; // true: opts/notes are already in a,i,u,e display order
  part: "A" | "B";
  topic: string;
  diff: Difficulty;
  stem: string;
  pres?: Block[];
  ans: OptionId;
  opts: Quad;
  notes: Quad;
  correct: string;
  why: readonly string[];
  en: string;
  terms: readonly string[];
  tags: readonly string[];
}

function mk(s: Spec): Question {
  const pos = LETTERS.indexOf(s.ans);
  const options: Question["options"][number][] = [];
  const optionNotes: Partial<Record<OptionId, string>> = {};
  let w = 1;
  LETTERS.forEach((letter, idx) => {
    const k = s.disp ? idx : idx === pos ? 0 : w++;
    options.push({ id: letter, text: s.opts[k] });
    optionNotes[letter] = s.notes[k];
  });
  const q: Question = {
    id: s.id,
    part: s.part,
    topicIds: [s.topic],
    lessonIds: [LESSON_OF[s.topic]],
    difficulty: s.diff,
    type: s.part === "B" ? "scenario" : "knowledge",
    stem: s.stem,
    options,
    correctOptionId: s.ans,
    explanation: {
      correct: s.correct,
      why: s.why,
      optionNotes,
      english: s.en,
      termIds: s.terms,
    },
    source: { kind: "original", attribution: "本サイト独自問題" },
    tags: s.tags,
  };
  if (s.pres) q.presentation = s.pres;
  return q;
}

