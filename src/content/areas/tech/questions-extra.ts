import type { Block, Difficulty, OptionId, Question } from "@/lib/content/types";

type Opt = readonly [text: string, note: string];

interface Spec {
  n: number;
  part: "A" | "B";
  topics: readonly string[];
  lessons: readonly string[];
  diff: Difficulty;
  stem: string;
  presentation?: Block[];
  /** options in display order a, i, u, e: [text, per-option note] */
  opts: readonly [Opt, Opt, Opt, Opt];
  ans: OptionId;
  correct: string;
  why: readonly string[];
  english: string;
  terms: readonly string[];
  tags: readonly string[];
}

const IDS = ["a", "i", "u", "e"] as const;

function q(s: Spec): Question {
  return {
    id: `q-tech-ext-${String(s.n).padStart(3, "0")}`,
    part: s.part,
    topicIds: s.topics,
    lessonIds: s.lessons,
    difficulty: s.diff,
    type: s.part === "B" ? "scenario" : "knowledge",
    stem: s.stem,
    ...(s.presentation ? { presentation: s.presentation } : {}),
    options: IDS.map((id, k) => ({ id, text: s.opts[k][0] })),
    correctOptionId: s.ans,
    explanation: {
      correct: s.correct,
      why: s.why,
      optionNotes: Object.fromEntries(IDS.map((id, k) => [id, s.opts[k][1]])),
      english: s.english,
      termIds: s.terms,
    },
    source: { kind: "original", attribution: "本サイト独自問題" },
    tags: s.tags,
  };
}

