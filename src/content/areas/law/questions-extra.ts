// 本サイト独自問題（拡張セット）。opts / notes は a, i, u, e の表示順で記述し、ans が正解の位置を指す。
const LESSON_OF: Record<string, string> = {
  "law-privacy": "law/privacy",
  "law-privacy-ops": "law/privacy",
  "law-unauthorized": "law/cyber-criminal",
  "law-cyber": "law/cyber-criminal",
  "law-ip": "law/ip-contract",
  "law-contract": "law/ip-contract",
  "law-standards-ethics": "law/ip-contract",
};

const LETTERS: OptionId[] = ["a", "i", "u", "e"];

type Quad = readonly [string, string, string, string];

interface Spec {
  id: string;
  part: "A" | "B";
  topic: string;
  diff: Difficulty;
  stem: string;
  pres?: Block[];
  ans: OptionId;
  opts: Quad;
  notes: Quad;
  correct: string;
  why: readonly string[];
  en: string;
  terms: readonly string[];
  tags: readonly string[];
}

function mk(s: Spec): Question {
  const options = LETTERS.map((id, idx) => ({ id, text: s.opts[idx] }));
  const optionNotes: Partial<Record<OptionId, string>> = {};
  LETTERS.forEach((id, idx) => {
    optionNotes[id] = s.notes[idx];
  });
  const q: Question = {
    id: s.id,
    part: s.part,
    topicIds: [s.topic],
    lessonIds: [LESSON_OF[s.topic]],
    difficulty: s.diff,
    type: s.part === "B" ? "scenario" : "knowledge",
    stem: s.stem,
    options,
    correctOptionId: s.ans,
    explanation: {
      correct: s.correct,
      why: s.why,
      optionNotes,
      english: s.en,
      termIds: s.terms,
    },
    source: { kind: "original", attribution: "本サイト独自問題" },
    tags: s.tags,
  };
  if (s.pres) q.presentation = s.pres;
  return q;
}

